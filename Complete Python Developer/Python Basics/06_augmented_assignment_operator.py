# Augmented assignment operator
some_value = 5

some_value += 2  # this will be 5 + 2 = 7

# essentially instead of doing some_value = some_value + 2 -> some_value += 2
# same thing can be done with other operators *= | -= etc..
some_value *= 2  # 5 * 2 = 10
some_value -= 2  # 5 - 2 = 3
some_value **= 2  # 5^2 = 25
