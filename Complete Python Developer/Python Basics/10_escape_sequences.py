# Escape sequence

weather = "It's sunny"  # You can either use "" or if you prefer single quotes you'd have to write 'It\'s sunny'
weather_two = 'It\'s "kind of" sunny'  # This will print -> It's "kind of" sunny
weather_three = '\tIt\'s "kind of" sunny'  # \t adds a tab
weather_four = (
    'It\'s "kind of" sunny \n hope you have a good day!'  # \n adds a new line
)
