A = 2
B = 4

print(A + B)
print(A - B)
print(A * B)
print(A / B)

# we can use the type() class on a value to see what type it is

print("Type:", A + B, type(A + B))
print("Type:", A - B, type(A - B))
print("Type:", A * B, type(A * B))
print("Type:", A / B, type(A / B))

